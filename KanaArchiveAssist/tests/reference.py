"""Independent dense Newton oracle. Development only."""
import math
from pathlib import Path
import sys
import numpy as np

def features(options, visions):
    result = []
    for ability in options:
        row = {f'a:{ability}': 1.0}
        for vision, count in visions:
            for k in range(1, 4):
                if count >= k:
                    row[f'b:{ability}:{vision}:{k}'] = 1.0
            if count > 3:
                row[f'b:{ability}:{vision}:4'] = math.log(count - 2)
        for other in options:
            if ability != other:
                row[f'c:{ability}:{other}'] = 1.0
        result.append(row)
    return result

def lua(v):
    if isinstance(v, dict):
        return '{' + ','.join('[' + lua(k) + ']=' + lua(x) for k, x in v.items()) + '}'
    if isinstance(v, (list, tuple, np.ndarray)):
        return '{' + ','.join(lua(x) for x in v) + '}'
    if isinstance(v, str):
        return '"' + v.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return format(float(v), '.17g')

def case(kind):
    n = 240 if kind == 'context' else 120
    observations = []
    for i in range(n):
        options = [1, 2, 3] if kind == 'triple' else [1, 2]
        visions = [[9, 1]] if kind == 'context' and i % 2 else []
        selected = (1 if i % 6 < 3 else 2 if i % 6 < 5 else 3) if kind == 'triple' else (2 if visions else 1) if kind == 'context' else (2 if i % 4 == 0 else 1)
        observations.append(dict(options=options, visions=visions, selected=selected))
    raw = [features(o['options'], o['visions']) for o in observations]
    keys = sorted({key for rows in raw for row in rows for key in row})
    matrices = [np.array([[row.get(k, 0.0) for k in keys] for row in rows]) for rows in raw]
    penalties = np.array([2.0 if k[0] == 'a' else 16.0 if k[0] == 'b' else 2.0 for k in keys])
    weights = [2 ** (-(math.ceil(n / 12) - math.ceil((i + 1) / 12)) / 30) for i in range(n)]
    def objective(theta):
        loss = .5 * np.dot(penalties * theta, theta)
        gradient = penalties * theta
        hessian = np.diag(penalties)
        for o, x, weight in zip(observations, matrices, weights):
            u = x @ theta
            e = np.exp(u - u.max()); p = e / e.sum()
            winner = o['options'].index(o['selected'])
            loss += weight * (u.max() + np.log(e.sum()) - u[winner])
            error = p.copy(); error[winner] -= 1
            gradient += weight * x.T @ error
            hessian += weight * x.T @ (np.diag(p) - np.outer(p, p)) @ x
        return loss, gradient, hessian
    theta = np.zeros(len(keys))
    for _ in range(100):
        loss, g, h = objective(theta)
        if np.max(np.abs(g)) < 1e-10:
            break
        direction = np.linalg.solve(h, -g)
        step = 1.0
        while objective(theta + step * direction)[0] > loss + 1e-4 * step * np.dot(g, direction):
            step *= .5
            if step < 1e-12:
                break
        theta += step * direction
    assert np.max(np.abs(objective(theta)[1])) < 1e-7
    x = matrices[0]; u = x @ theta; p = np.exp(u - u.max()); p /= p.sum()
    return dict(name=kind, observations=observations, keys=keys, theta=theta,
                loss=objective(theta)[0], probabilities=p)

