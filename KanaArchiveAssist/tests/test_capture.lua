local T=KAATest;T.load('Config');local R=T.load('RunCapture')
local function fixture()
 local rows={};local now=0;local r=R.New(function(o)rows[#rows+1]=o end,function()return now end)
 local o=T.observation(1,1,1,{{9,2}});o.offerId='o1';r:Open(o)
 return r,rows,o,function(t)now=t end
end
T.test('confirm hide result owns profile and old context exactly once',function()
 local r,rows,o=fixture();assert(r:Confirm(1,'p1',0));o.context.visions[1][2]=3;r:Hide()
 assert(r:ApplyResult(0,1,1,0,false));assert(not r:ApplyResult(0,1,1,0,false));T.eq(#rows,1)
 T.eq(rows[1].context.visions[1][2],2);T.eq(rows[1].profileId,'p1')
end)
T.test('hover random result reroll mismatch and timeout do not teach',function()
 local r,rows,o,time=fixture();assert(not r:ApplyResult(0,1,1,0,false))
 r:Confirm(1,'p1',0);assert(not r:ApplyResult(0,2,1,0,false));T.eq(#rows,0)
 r:Confirm(1,'p1',0);r:Invalidate('reroll');assert(not r:ApplyResult(0,1,1,0,false))
 r:Open(o);r:Confirm(1,'p1',0);time(31);assert(not r:ApplyResult(0,1,1,0,false))
end)
T.test('exclusion belongs to one offer and freezes at confirmation',function()
 local r,rows,o=fixture();assert(r:SetExcluded('o1',true));assert(r:IsExcluded('o1'))
 r:Open(o);assert(r:IsExcluded('o1'));assert(not r:SetExcluded('stale',false))
 assert(r:Confirm(1,'p1',0));assert(not r:SetExcluded('o1',false));r:Hide()
 local recorded,matched=r:ApplyResult(0,1,1,0,false);assert(not recorded and matched);T.eq(#rows,0)
 o.offerId='o2';r:Open(o);assert(not r:IsExcluded('o2'))
 assert(r:Confirm(1,'p2',1));assert(r:ApplyResult(0,1,2,1,false));T.eq(rows[1].profileId,'p2')
end)
T.test('exclusion can be undone before confirming and reroll clears it',function()
 local r,rows,o=fixture();assert(r:SetExcluded('o1',true));assert(r:SetExcluded('o1',false));assert(not r:IsExcluded('o1'))
 r:Confirm(1,'p1',0);assert(r:ApplyResult(0,1,1,0,false));T.eq(#rows,1)
 r:SetExcluded('o1',true);r:Invalidate();o.offerId='rerolled';r:Open(o);assert(not r:IsExcluded('rerolled'))
end)
T.test('restore and ambiguous transitions do not teach',function()
 local r,rows=fixture();r:Confirm(1,'p1',0);assert(not r:ApplyResult(0,1,1,0,true))
 r:Confirm(1,'p1',0);assert(not r:ApplyResult(0,1,2,0,false));T.eq(#rows,0)
end)
T.test('capture reports pending acknowledgement timeout exclusion and rejected history',function()
 local states,now,rows={},0,0
 local r=R.New(function()rows=rows+1;return false end,function()return now end,nil,function(s)states[#states+1]=s end)
 local o=T.observation(1,1);o.offerId='one';r:Open(o);T.eq(r.status.state,'offered')
 r:Confirm(1,'p1',0);r:Hide();T.eq(r.status.state,'pending')
 now=31;assert(r:CheckTimeout());T.eq(r.status.state,'failed');T.eq(r.status.reason,'timeout');T.eq(r.status.profileId,'p1');T.eq(rows,0)
 r:Confirm(1,'p1',0);local recorded,matched=r:ApplyResult(0,1,1,0,false);assert(not recorded and matched);T.eq(r.status.reason,'history_rejected')
 r:SetExcluded('one',true);T.eq(r.status.state,'excluded_offer');r:Confirm(1,'p1',0);r:ApplyResult(0,1,1,0,false);T.eq(r.status.state,'excluded')
 r:SetExcluded('one',false);r:Confirm(1,'p1',0);r:ApplyResult(0,2,1,0,false);T.eq(r.status.reason,'mismatched_result')
 r:Confirm(1,'p1',0);o.offerId='next';r:Open(o);T.eq(states[#states-1].reason,'offer_replaced');T.eq(r.status.state,'offered')
end)
