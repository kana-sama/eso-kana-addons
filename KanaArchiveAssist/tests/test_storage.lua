local T=KAATest;T.load('Config');local P=T.load('Profiles');local H=T.load('History')
T.test('default stable across rename and characters',function()
 local sv={};local p=P.New(sv,'EU','one',string.lower);local id=p:GetActive().id
 assert(p:Rename(id,' Tank '));local q=P.New(sv,'EU','two',string.lower)
 T.eq(q:GetActive().id,id);T.eq(q:GetActive().name,'Tank');T.eq(#q:List(),1)
 T.eq(P.New(sv,'NA','one',string.lower):GetActive().name,'default')
end)
T.test('name errors and profile switches preserve history',function()
 local p=P.New({},'EU','one',string.lower);local old=p:GetActive().id
 assert(not p:Create('  '));assert(not p:Create('|cffffffbad'));assert(not p:Create('DEFAULT'))
 p:GetActive().history[1]={saved=true};local new=p:Create('Healer');assert(new);T.eq(p:GetActive().id,new.id)
 assert(p:Use(old));assert(p:GetActive().history[1].saved);assert(not p:Use('missing'))
end)
T.test('history keeps full data, caps window and deduplicates',function()
 local profile={id='p1'};local h=H.New(profile)
 for i=1,2001 do assert(h:Append(T.observation(i,math.ceil(i/10)))) end
 assert(not h:Append(T.observation(2001,201)))
 local d=h:BuildDataset(0);T.eq(#d.rows,2000);T.eq(#profile.history,2001)
 T.eq(h:GetRevision(0),2001);T.eq(d.rows[1].observation.observationId,'2')
end)
T.test('age counts only training runs of same type and profile',function()
 local h=H.New({id='p1'});for i=1,31 do h:Append(T.observation(i,i)) end
 local d=h:BuildDataset(0);T.near(d.rows[1].weight,0.5);T.near(d.rows[31].weight,1)
 local other=T.observation(32,32);other.buffType=1;h:Append(other)
 T.near(h:BuildDataset(0).rows[1].weight,0.5)
end)
T.test('snapshot owns context and invalid data is isolated',function()
 local profile={id='p1'};local h=H.New(profile);local o=T.observation(1,1,1,{{9,2}})
 assert(h:Append(o));o.context.visions[1][2]=9
 T.eq(h:BuildDataset(0).rows[1].observation.context.visions[1][2],2)
 local bad=T.observation(2,2);bad.selectedId=99;assert(not h:Append(bad));T.eq(#profile.history,1)
end)
T.test('future schema preserved without training',function()
 local profile={id='p1',schemaVersion=99,history={T.observation(1,1)}};local h=H.New(profile)
 assert(not h:Append(T.observation(2,2)));T.eq(#profile.history,1);assert(h:BuildDataset(0).unavailable)
end)
T.test('malformed context cannot enter a training dataset',function()
 local h=H.New({id='p1'});local o=T.observation(1,1);o.context=nil;assert(not h:Append(o))
 o.context={visions='bad'};assert(not h:Append(o))
end)
T.test('profile summary counts accepted history across types and survives reload',function()
 local profile={id='p1'};local h=H.New(profile)
 local a=T.observation(1,1);assert(h:Append(a))
 local b=T.observation(2,1,2);b.buffType=1;assert(h:Append(b))
 local c=T.observation(3,2,2);c.recordedAt=100;c.recordedTime='12:34:56';c.recordedDate='15.10.2026';assert(h:Append(c))
 assert(not h:Append(c));local invalid=T.observation(4,2);invalid.selectedId=9;assert(not h:Append(invalid))
 local s=h:GetSummary('2');T.eq(s.total,3);T.eq(s.runs,2);T.eq(s.currentRun,1);T.eq(s.byType[0],2);T.eq(s.byType[1],1)
 T.eq(s.last.selectedId,2);T.eq(s.last.recordedAt,100);c.selectedId=9;T.eq(h:GetSummary('2').last.selectedId,2)
 s.last.context.visions[1]={99,1};T.eq(#h:GetSummary('2').last.context.visions,0)
 local restored=H.New(KanaArchiveAssist.Config.Copy(profile)):GetSummary('1');T.eq(restored.total,3);T.eq(restored.currentRun,2);T.eq(restored.last.recordedTime,'12:34:56')
 local old=H.New({id='p1',history={a}}):GetSummary('1');assert(not old.last.recordedAt)
 assert(H.New({id='p1',schemaVersion=99,history={a}}):GetSummary('1').unavailable)
end)
