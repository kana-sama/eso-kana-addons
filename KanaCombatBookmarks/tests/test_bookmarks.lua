local T = dofile('KanaCombatBookmarks/tests/support.lua')
T.test('bookmark implementation', function() T.load('Names'); T.load('Model'); T.load('Integration') end)
if T.failed > 0 then T.finish() end
local function setup()
    local a = T.api()
    return a, KanaCombatBookmarks.Integration.Install(a)
end
T.test('one exact marker, name and click per press; no log writes or scans', function()
    local a, b = setup(); a:start()
    a.CMX.currentdata.log = setmetatable(a.CMX.currentdata.log, {__pairs = function() error('log scanned') end})
    a.now = 112345
    local entry = assert(b:Mark())
    T.eq(entry.offsetMs, 12345); T.eq(entry.id, 1)
    assert(a.alerts[1]:find(entry.name, 1, true)); assert(a.alerts[1]:find('00:12.345', 1, true))
    T.eq(#a.CMX.currentdata.log, 1); T.eq(a.sounds[1], 'Lockpicking_chamber_locked')
    local other = assert(b:Mark())
    assert(other.name ~= entry.name); T.eq(other.offsetMs, 12345); T.eq(other.id, 2)
    T.eq(#a.sounds, 2); T.eq(#a.alerts, 2)
end)
T.test('inactive or light mode rejects without success sound or consuming a name', function()
    local a, b = setup(); assert(not b:Mark()); T.eq(#a.sounds, 0)
    a:start(); a.CMX.db.lightmode = true; assert(not b:Mark())
    a.CMX.db.lightmode = false; T.eq(assert(b:Mark()).id, 1)
    a.ava = true; a.CMX.db.lightmodeincyrodil = true; assert(not b:Mark())
    a.CMX.db.lightmodeincyrodil = false; a.CMX.db.offincyrodil = true; assert(not b:Mark())
    T.eq(#a.sounds, 1)
end)
T.test('finalization uses actual combatstart and attaches before an earlier save callback', function()
    local a, b = setup(); a:start(100000); a.now = 112345
    local mark = assert(b:Mark()); a:stop(120000)
    local fight = a:finish(100007, 120000, true)
    T.eq(mark.offsetMs, 12338)
    T.eq(fight.kanaCombatBookmarks.entries[1], mark)
    T.eq(a.saves[1], fight.kanaCombatBookmarks)
    T.eq(#a.sounds, 1)
end)
T.test('death, end grace and new fight ownership', function()
    local a, b = setup(); a:start(); a.now = 101000; assert(b:Mark())
    a:stop(102000); a.now = 102500; assert(b:Mark())
    local old = a:finish(100000, 102000)
    a.now = 112000; T.eq(assert(b:Mark()).offsetMs, 12000)
    a.now = 112001; assert(not b:Mark())
    a:start(113000); local new = assert(b:Mark()); T.eq(new.id, 1)
    local fight = a:finish(113000, 114000)
    T.eq(#old.kanaCombatBookmarks.entries, 3)
    T.eq(#fight.kanaCombatBookmarks.entries, 1)
end)
T.test('reentering same fight preserves origin; changed current log and manual reset do not mix markers', function()
    local a, b = setup(); a:start(); a.now = 100200; assert(b:Mark())
    a:stop(100300); a:start(100400); T.eq(assert(b:Mark()).offsetMs, 400)
    local old = a:finish(100000, 100500)
    a:start(100500); T.eq(assert(b:Mark()).id, 1)
    T.eq(#old.kanaCombatBookmarks.entries, 2)
    a.CMX.currentdata = {log = {}}; assert(not b:Mark())
end)
T.test('install is idempotent', function()
    local a, b = setup(); T.eq(KanaCombatBookmarks.Integration.Install(a), b)
    a:start(); b:Mark(); T.eq(#a.sounds, 1)
end)
T.test('actual CMX serialization retains names and times without changing or duplicating events', function()
    local storage = T.storage()
    local a, b = setup(); a.CombatMetricsFightData = storage
    a:start(100000); a.now = 112345; local entry = assert(b:Mark()); a:stop(120000)
    local fight = a:finish(100000, 120000)
    fight.starttime = fight.combatstart
    fight.APIversion = 101050
    fight.units = {}; fight.calculated = {units = {}, DPSOut = 1, DPSIn = 0, HPSOut = 0, HPSIn = 0}
    storage.Save(fight, true)
    local restored = storage.Load(1)
    T.eq(restored.kanaCombatBookmarks.entries[1].name, entry.name)
    T.eq(restored.kanaCombatBookmarks.entries[1].offsetMs, 12345)
    T.eq(#restored.log, 2); T.eq(#fight.log, 2); T.eq(fight.log[1][2], 100000)
    T.eq(#storage.Load(1).kanaCombatBookmarks.entries, 1); T.eq(#a.sounds, 1)
    storage.Save(fight, {})
    restored = storage.Load(2)
    T.eq(restored.log, nil); T.eq(restored.kanaCombatBookmarks.entries[1].name, entry.name)
end)
T.test('summary before re-registered CMX retains metadata through another fight and GC', function()
    local a,b=setup();a:start(100000);a.now=100100;local mark=assert(b:Mark());a:stop(101000)
    local fight={combatstart=100007,combatend=101000}
    a.callbacks[2](2,fight) -- CMX moved behind this callback after a recording-mode toggle.
    fight.log=a.CMX.currentdata.log;a.CMX.currentdata={log={}};a.CMX.lastfights[1]=fight
    T.eq(assert(fight.kanaCombatBookmarks).entries[1],mark);T.eq(mark.offsetMs,93)
    a.now=101500;assert(b:Mark());T.eq(#fight.kanaCombatBookmarks.entries,2)
    a:start(102000);collectgarbage('collect');a.CombatMetricsFightData.Save(fight)
    T.eq(a.saves[1],fight.kanaCombatBookmarks);T.eq(#fight.kanaCombatBookmarks.entries,2)
end)
T.finish()
