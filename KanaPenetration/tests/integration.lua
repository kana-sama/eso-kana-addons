return function(T)
    local entry=loadfile('KanaPenetration/Core.lua')
    T.test('HUD implementation exists',function()assert(entry,'implement HUD and lifecycle')end)
    if not entry then return end
    local function setup()
        local h=dofile('KanaPenetration/tests/harness.lua')();local k=h.load()
        h.fragments[1]:Show();return h,k
    end
    T.test('one scene root shared by both HUD modes',function()
        local h,k=setup();T.eq(#h.fragments,2);T.eq(h.fragments[1],h.fragments[2])
        T.eq(k.view.root.mouse,false);T.eq(h.events[EVENT_ADD_ON_LOADED],nil)
    end)
    T.test('one centered label contains only penetration and percent',function()
        local h,k=setup();local row=k.view.rows[1]
        T.eq(row.text.text,'7K ≈77%');T.eq(row.text.horizontalAlignment,TEXT_ALIGN_CENTER)
        T.eq(row.text.verticalAlignment,TEXT_ALIGN_CENTER);T.eq(row.text.font,'EsoBold|18|soft-shadow-thick')
        T.eq(row.title,nil);T.eq(row.percent,nil);T.eq(row.numbers,nil);T.eq(k.view.note,nil)
        T.eq(k.view.rows[2].root.hidden,true)
    end)
    T.test('target HP fill and reverse half use native target templates',function()
        local h,k=setup();local row=k.view.rows[1]
        T.eq(row.bars[1].template,'ZO_TargetAttributeStatusBar_Keyboard_Template')
        T.eq(row.bars[1].barAlignment,BAR_ALIGNMENT_REVERSE)
        T.near(row.bars[1].value,7000/9100);T.eq(row.bars[1].value,row.bars[2].value)
        T.eq(row.gloss[1].value,row.bars[1].value)
        T.eq(row.frame.Left.texture,h.target:GetNamedChild('FrameLeft').texture)
        h.physical=12000;h.spell=12000;h.tick()
        T.eq(row.bars[1].value,1);T.eq(row.text.text,'12K ≈132%')
        assert(row.bars[1].color[1] < .6 and row.gloss[1].color[1] < .6,
            'bright fill or gloss obscures the white numbers')
    end)
    T.test('bar continues HP side lines and inserts space before the name',function()
        local h,k=setup();local view=k.view
        T.eq(view.root.anchor[2],h.hp);T.eq(view.root:GetTop(),h.hp:GetBottom()+3)
        T.near(view.rows[1].width,281-2*26*14/17)
        T.near(view.rows[1].root:GetLeft(),h.hp:GetLeft()+(h.hp:GetHeight()+3*h.target:GetScale())*14/17)
        T.eq(h.targetText.anchor[2],view.root)
        T.eq(h.targetText:GetTop(),view.root:GetBottom()+7)
        h.target:SetAnchor(TOP,GuiRoot,TOP,100,200)
        T.eq(view.root:GetTop(),h.hp:GetBottom()+3);T.eq(view.root:GetCenter(),1060)
        T.eq(h.target:GetWidth(),281);T.eq(h.target:GetHeight(),23)
    end)
    T.test('second row follows the same slopes without labels',function()
        local h,k=setup();h.physical=3000;h.tick()
        T.eq(k.view.rows[2].root.hidden,false)
        T.eq(k.view.rows[1].text.text,'3K ≈33%');T.eq(k.view.rows[2].text.text,'7K ≈77%')
        T.near(k.view.rows[1].width-k.view.rows[2].width,2*26*14/17)
        T.near(k.view.rows[2].root:GetLeft()-k.view.rows[1].root:GetLeft(),26*14/17)
        T.eq(k.view.root:GetHeight(),49)
    end)
    T.test('font comes from displayed native HP before an idle LUI label',function()
        local h,k=setup();h.luiNumbers.text='40k';h.luiNumbers.fontSize=20;h.tick()
        T.eq(k.view.rows[1].text.font,'EsoBold|18|soft-shadow-thick')
        h.healthNumbers.fontSize=19;h.tick()
        T.eq(k.view.rows[1].text.font,'EsoBold|19|soft-shadow-thick')
        h.healthNumbers:SetHidden(true);h.tick()
        T.eq(k.view.rows[1].text.font,'LuiFont|20|soft-shadow-thick')
        h.healthNumbers:SetHidden(false);h.healthNumbers.text='';h.tick()
        T.eq(k.view.rows[1].text.font,'LuiFont|20|soft-shadow-thick')
        h.healthNumbers.text='40K';h.healthNumbers.alpha=0;h.tick()
        T.eq(k.view.rows[1].text.font,'LuiFont|20|soft-shadow-thick')
    end)
    T.test('HP font uses the resolved face instead of treating a descriptor as a face',function()
        local h,k=setup()
        h.healthNumbers.font='$(BOLD_FONT)|18|soft-shadow-thick'
        h.healthNumbers.face='EsoUI/Common/Fonts/Univers67.slug'
        h.tick()
        T.eq(k.view.rows[1].text.font,'EsoUI/Common/Fonts/Univers67.slug|18|soft-shadow-thick')
        h.healthNumbers.font='ZoFontWinH5';h.healthNumbers.fontSize=18.5;h.healthNumbers.fontStyle=''
        h.tick()
        T.eq(k.view.rows[1].text.font,'EsoUI/Common/Fonts/Univers67.slug|18.5')
        h.healthNumbers:SetHidden(true);h.luiNumbers.text='321,8K 100%'
        h.luiNumbers.font='CustomBold|20|outline';h.luiNumbers.face='CustomBold'
        h.luiNumbers.fontSize=20;h.luiNumbers.fontStyle='outline';h.tick()
        T.eq(k.view.rows[1].text.font,'CustomBold|20|outline')
    end)
    T.test('native localization abbreviates penetration and formats percentages',function()
        local h,k=setup();h.physical=11420;h.spell=11420;h.tick()
        T.eq(k.view.rows[1].text.text,'11,4K ≈125%');assert(h.abbreviationCalls>0)
        h.physical=450;h.spell=450;h.tick()
        T.eq(k.view.rows[1].text.text,'450 ≈4,9%')
    end)
    T.test('bar always follows HP despite saved floating layout',function()
        local h,k=setup();h.saved.attachToTarget=false
        h.saved.width=600;h.saved.scale=2;h.saved.targetX=500;h.saved.targetY=90
        h.target:SetScale(1.5);h.tick()
        T.near(k.view.root:GetWidth(),(281-2*26*14/17)*1.5)
        T.eq(k.view.root:GetTop(),h.hp:GetBottom()+4.5)
        T.near(k.view.rows[1].root:GetLeft(),h.hp:GetLeft()+(h.hp:GetHeight()+3*h.target:GetScale())*14/17)
        T.eq(k.view.rows[1].text.font,'EsoBold|18|soft-shadow-thick')
        T.eq(h.targetText.anchor[2],k.view.root)
        T.eq(k.view.root.mouse,false);T.eq(k.view.root.movable,false)
        T.eq(k.view.root.handlers.OnMoveStart,nil);T.eq(k.view.root.handlers.OnMoveStop,nil)
        for _,option in ipairs(h.options) do
            assert(option.name~='Переместить полосу' and option.name~='Ширина'
                and option.name~='Масштаб' and option.name~='Сбросить положение')
        end
    end)
    T.test('native name anchor restores on lost target, disable, menu and new anchors',function()
        local h,k=setup();h.exists=false;h.target:SetHidden(true);h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(h.targetText.anchor[2],h.target);T.eq(h.targetText.anchor[5],7)
        h.exists=true;h.target:SetHidden(false);h.fire(EVENT_RETICLE_TARGET_CHANGED)
        h.option('Включить').setFunc(false);T.eq(h.targetText.anchor[2],h.target)
        h.option('Включить').setFunc(true);h.fragments[1]:Hide();T.eq(h.targetText.anchor[2],h.target)
        h.fragments[1]:Show();h.targetText:SetAnchor(TOP,h.target,BOTTOM,3,12);h.tick()
        h.exists=false;h.target:SetHidden(true);h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(h.targetText.anchor[4],3);T.eq(h.targetText.anchor[5],12)
        T.eq(h.caption.anchor[2],h.targetText)
    end)
    T.test('new target never retains old debuffs',function()
        local h,k=setup();h.buffs={{id=61743}};h.tick()
        T.eq(k.view.rows[1].text.text,'7K ≈222%')
        h.buffs={};h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.rows[1].text.text,'7K ≈77%')
    end)
    T.test('expired debuff disappears on next tick',function()
        local h,k=setup();h.buffs={{id=61743,finish=11}};h.tick();h.now=12;h.tick()
        T.eq(k.view.rows[1].text.text,'7K ≈77%')
    end)
    T.test('menus stop polling and do not reveal HUD after target changes',function()
        local h,k=setup();h.fragments[1]:Hide();T.eq(next(h.updates),nil)
        h.fire(EVENT_RETICLE_TARGET_CHANGED);T.eq(k.view.root.hidden,true);T.eq(next(h.updates),nil)
        h.physical=4000;h.spell=4000;h.fragments[1]:Show()
        T.eq(k.view.rows[1].text.text,'4K ≈44%');assert(next(h.updates))
    end)
    T.test('target lost stops polling; new target resumes',function()
        local h,k=setup();h.exists=false;h.target:SetHidden(true);h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.content.hidden,true);T.eq(next(h.updates),nil)
        h.exists=true;h.target:SetHidden(false);h.fire(EVENT_RETICLE_TARGET_CHANGED);T.eq(k.view.content.hidden,false);assert(next(h.updates))
    end)
    T.test('lost target follows native fade and keeps split rows and name until hidden',function()
        local h,k=setup();h.physical=3000;h.tick()
        h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.content.hidden,false);T.eq(next(h.updates),nil)
        T.eq(k.view.rows[2].root.hidden,false);T.eq(h.targetText.anchor[2],k.view.root)
        local text=k.view.rows[1].text.text
        k.observer.Capture=function() error('fade must not capture stats') end
        k.view.Layout=function() error('fade must not rebuild layout') end
        for _,alpha in ipairs({.9,.7,.4,.1,0}) do
            h.target:SetAlpha(alpha);h.frame();T.eq(k.view.content:GetAlpha(),alpha)
            T.eq(k.view.rows[1].text.text,text);T.eq(h.targetText.anchor[2],k.view.root)
        end
        h.target:SetHidden(true);h.frame()
        T.eq(k.view.content.hidden,true);T.eq(k.view.root.handlers.OnUpdate,nil)
        T.eq(h.targetText.anchor[2],h.target);T.eq(next(h.updates),nil)
    end)
    T.test('fade reversal and new target use fresh data and native alpha',function()
        local h,k=setup();h.buffs={{id=61743}};h.tick()
        h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED);h.target:SetAlpha(.3);h.frame()
        h.exists=true;h.buffs={};h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.rows[1].text.text,'7K ≈77%');T.eq(k.view.content:GetAlpha(),.3)
        h.target:SetAlpha(.8);h.frame();T.eq(k.view.content:GetAlpha(),.8)
        h.player=true;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.content.hidden,true);T.eq(k.view.root.handlers.OnUpdate,nil)
    end)
    T.test('menus and disable cancel retained fade immediately',function()
        local h,k=setup();h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        h.fragments[1]:Hide();T.eq(k.view.root.handlers.OnUpdate,nil)
        T.eq(h.targetText.anchor[2],h.target)
        h.fragments[1]:Show();T.eq(k.view.content.hidden,true)
        h.exists=true;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        h.option('Включить').setFunc(false)
        T.eq(k.view.content.hidden,true);T.eq(k.view.root.handlers.OnUpdate,nil)
    end)
    T.test('unchanged target ticks do not rewrite labels, textures or anchors',function()
        local h,k=setup();local calls=0
        for _,control in pairs(h.controls) do
            for _,method in ipairs({'SetText','SetFont','SetTexture','SetTextureCoords','SetAnchor','SetDimensions','SetValue','SetColor'}) do
                local original=control[method]
                control[method]=function(self,...) calls=calls+1;return original(self,...) end
            end
        end
        for i=1,20 do h.tick();h.frame() end
        T.eq(calls,0)
    end)
    T.test('initial fade in waits for native visibility without losing the target',function()
        local h,k=setup();h.target:SetHidden(true);h.target:SetAlpha(0)
        h.fire(EVENT_RETICLE_TARGET_CHANGED);T.eq(k.view.content:GetAlpha(),0)
        h.frame();T.eq(k.view.visible,true)
        h.target:SetHidden(false);h.target:SetAlpha(.25);h.frame()
        T.eq(k.view.content:GetAlpha(),.25);T.eq(h.targetText.anchor[2],k.view.root)
    end)
    T.test('legacy detached setting still follows native target fade',function()
        local h,k=setup();h.saved.attachToTarget=false
        h.target:SetAlpha(.2);h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.content:GetAlpha(),.2);assert(k.view.root.handlers.OnUpdate)
        h.target:SetHidden(true);h.frame();T.eq(k.view.content.hidden,true)
        T.eq(next(h.updates),nil)
    end)
    T.test('repeated appearance and disappearance reuse controls and leave no updates',function()
        local h,k=setup();local count=h.controlsCreated
        for i=1,1000 do
            h.exists=false;h.fire(EVENT_RETICLE_TARGET_CHANGED)
            h.target:SetAlpha(.5);h.frame()
            h.target:SetHidden(true);h.frame()
            T.eq(next(h.updates),nil);T.eq(k.view.root.handlers.OnUpdate,nil)
            T.eq(h.targetText.anchor[2],h.target)
            h.target:SetHidden(false);h.target:SetAlpha(1);h.exists=true
            h.fire(EVENT_RETICLE_TARGET_CHANGED)
            T.eq(h.targetText.anchor[2],k.view.root)
        end
        T.eq(h.controlsCreated,count)
    end)
    T.test('dead or player targets hide the bar',function()
        local h,k=setup();h.dead=true;h.tick();T.eq(k.view.content.hidden,true)
        h.dead=false;h.player=true;h.fire(EVENT_RETICLE_TARGET_CHANGED);T.eq(k.view.content.hidden,true)
    end)
    T.test('Archive profile fills the bar for regular foes and Tho’at',function()
        local h,k=setup();h.archive=true;h.fire(EVENT_PLAYER_ACTIVATED)
        T.eq(k.view.rows[1].text.text,'7K ≈77%')
        h.name='То’ат Копировальщица';h.fire(EVENT_RETICLE_TARGET_CHANGED)
        T.eq(k.view.rows[1].text.text,'7K ≈38%')
    end)
    T.test('unknown resistance is visibly unknown',function()
        local h,k=setup();h.zone=0;h.fire(EVENT_PLAYER_ACTIVATED)
        T.eq(k.view.rows[1].text.text,'7K ?')
        T.eq(k.view.rows[1].bars[1].value,0)
        T.eq(k.view.rows[1].bars[1]:IsControlHidden(),false)
    end)
    T.test('zero resistance uses explicit stripped state',function()
        local h,k=setup();h.buffs={{id=61743},{id=61742},{id=17906}};h.tick()
        T.eq(k.view.rows[1].text.text,'7K —');T.eq(k.view.rows[1].bars[1].value,1)
    end)
    T.test('Force of Nature shows interval rather than false exact percent',function()
        local h,k=setup();h.fon=true;h.tick()
        T.eq(k.view.rows[1].text.text,'7K–12,3K ≈77–135%')
    end)
    T.test('settings apply immediately without reload',function()
        local h,k=setup();h.option('Профиль сопротивления').setFunc('dungeon')
        T.eq(k.view.rows[1].text.text,'7K ≈38%')
        h.option('Показывать числа').setFunc(false);T.eq(k.view.rows[1].text.hidden,true)
        h.option('Включить').setFunc(false);T.eq(k.view.content.hidden,true);T.eq(next(h.updates),nil)
        h.option('Включить').setFunc(true);T.eq(k.view.content.hidden,false)
    end)
    T.test('screen resizing never changes HP attachment or bar dimensions',function()
        local h,k=setup();local width=k.view.root:GetWidth()
        GuiRoot:SetDimensions(300,180);h.fire(EVENT_SCREEN_RESIZED)
        T.eq(k.view.root.anchor[2],h.hp);T.eq(k.view.root:GetWidth(),width)
        T.eq(k.view.root.clamped,false)
    end)
    T.test('settings need no slash command',function()
        local h=setup();T.eq(SLASH_COMMANDS['/kpen'],nil)
        assert(h.panel and h.option('Профиль сопротивления'))
    end)
    T.test('missing target frame hides the bar and binds when frame becomes available',function()
        local h=dofile('KanaPenetration/tests/harness.lua')()
        ZO_TargetUnitFramereticleover=nil
        local k=h.load();h.fragments[1]:Show()
        T.eq(k.view.content.hidden,true)
        T.eq(next(h.updates),nil)
        ZO_TargetUnitFramereticleover=h.target;h.fire(EVENT_PLAYER_ACTIVATED)
        T.eq(k.view.root.anchor[2],h.hp)
    end)
    T.test('hiding never restores an obsolete anchor over a newer addon anchor',function()
        local h,k=setup();h.targetText:SetAnchor(TOP,h.target,BOTTOM,9,30)
        h.fragments[1]:Hide()
        T.eq(h.targetText.anchor[4],9);T.eq(h.targetText.anchor[5],30)
    end)
end
